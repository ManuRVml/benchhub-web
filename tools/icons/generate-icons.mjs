#!/usr/bin/env node
// Generates src/shared/ui/icons/<Name>Icon.tsx + index.ts from tools/icons/icons.json (P5-10). No dependencies.
// Usage: node tools/icons/generate-icons.mjs   Then run Prettier on src/shared/ui/icons (the pre-commit hook checks it).
// Components draw exactly the elements recorded in icons.json; colour is always currentColor.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { ICONS_DIR, ICONS_JSON, jsxAttr, pascalCase } from './lib.mjs';

/** @type {Array<{ name: string, context: string, viewBox: string, width: number | null, strokeWidth: number | null,
 *   strokeLinecap: string | null, strokeLinejoin: string | null,
 *   elements: Array<{ tag: string, attrs: Record<string, string> }>, htmlLines: number[] }>} */
const icons = JSON.parse(readFileSync(ICONS_JSON, 'utf8'));
const HEADER =
  '// Generated by tools/icons/generate-icons.mjs from tools/icons/icons.json — do not edit by hand.';

/** @param {{ tag: string, attrs: Record<string, string> }} element */
function jsxElement({ tag, attrs }) {
  const props = Object.entries(attrs).map(([name, value]) => `${jsxAttr(name)}="${value}"`);
  return `<${tag} ${props.join(' ')} />`;
}

mkdirSync(ICONS_DIR, { recursive: true });
for (const file of readdirSync(ICONS_DIR)) {
  if (/Icon\.tsx$/.test(file)) rmSync(join(ICONS_DIR, file));
}

const exports = [];
for (const icon of icons) {
  const component = `${pascalCase(icon.name)}Icon`;
  const rootProps = [
    `viewBox="${icon.viewBox}"`,
    'fill="none"',
    'stroke="currentColor"',
    icon.strokeWidth === null ? null : `strokeWidth={${String(icon.strokeWidth)}}`,
    icon.strokeLinecap === null ? null : `strokeLinecap="${icon.strokeLinecap}"`,
    icon.strokeLinejoin === null ? null : `strokeLinejoin="${icon.strokeLinejoin}"`,
  ].filter(Boolean);
  const source = `${HEADER}
// Prototype: ${icon.context}; BencHUD.dc.html L${icon.htmlLines.join(', L')}.
import { forwardRef } from 'react';

import { iconA11yProps } from './icon-props';

import type { IconProps } from './icon-props';

export const ${component} = forwardRef<SVGSVGElement, IconProps>(function ${component}(
  { size = ${String(icon.width ?? 20)}, title, ...props },
  ref,
) {
  return (
    <svg
      ref={ref}
      width={size}
      height={size}
      ${rootProps.join('\n      ')}
      {...iconA11yProps(title)}
      {...props}
    >
      {title === undefined ? null : <title>{title}</title>}
      ${icon.elements.map(jsxElement).join('\n      ')}
    </svg>
  );
});
`;
  writeFileSync(join(ICONS_DIR, `${component}.tsx`), source);
  exports.push(`export { ${component} } from './${component}';`);
}

writeFileSync(
  join(ICONS_DIR, 'index.ts'),
  `${HEADER}
export type { IconProps } from './icon-props';
${exports.join('\n')}
`,
);
console.log(`generated ${String(icons.length)} icon components in src/shared/ui/icons`);
