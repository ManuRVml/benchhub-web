import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const screensDir = path.join(__dirname, '..', 'docs', 'design', 'screen-inventory');
const contractsDir = path.join(__dirname, '..', 'docs', 'design', 'view-data-contracts');
const outputScreen = path.join(__dirname, '..', 'docs', 'design', 'screen-inventory.md');
const outputContracts = path.join(__dirname, '..', 'docs', 'design', 'view-data-contracts.md');

function extractRouteText(text) {
  // Try to extract the first backtick-quoted token (the route path)
  const backtickMatch = text.match(/`([^`]+)`/);
  if (backtickMatch) {
    return backtickMatch[1];
  }
  // Otherwise, take text up to first ' — ' or ';'
  const parts = text.split(/ — |;/);
  return parts[0].trim();
}

function escapePipe(str) {
  return str.replace(/\|/g, '\\|');
}

function readScreenFiles() {
  const files = fs.readdirSync(screensDir).filter((f) => f.startsWith('SCR-') && f.endsWith('.md'));
  const screens = [];
  for (const file of files) {
    const fullPath = path.join(screensDir, file);
    const content = fs.readFileSync(fullPath, 'utf8');
    const lines = content.split('\n');

    // Extract ID from filename
    const fileMatch = file.match(/^SCR-(\d+)-/);
    const fileId = fileMatch ? `SCR-${fileMatch[1].padStart(2, '0')}` : '';
    const fileNumber = fileMatch ? parseInt(fileMatch[1], 10) : 0;

    // First line should be ## SCR-xx — <name>
    let name = '';
    let route = '';

    for (const line of lines) {
      if (line.startsWith('## ') && !name) {
        const match = line.match(/^## (.+)$/);
        if (match) {
          name = match[1];
          continue;
        }
      }
      if (line.startsWith('- Proposed route:')) {
        const match = line.match(/^- Proposed route:\s*(.+)$/);
        if (match) {
          route = extractRouteText(match[1]);
          break; // First route only
        }
      }
    }

    if (name) {
      // Remove the leading SCR-xx — prefix from the name
      const cleanName = name.replace(/^SCR-\d+\s+—\s+/, '');
      screens.push({
        id: fileId,
        number: fileNumber,
        name: cleanName,
        route,
        file,
      });
    }
  }
  return screens.sort((a, b) => a.number - b.number);
}

function readContractFiles() {
  if (!fs.existsSync(contractsDir)) return [];

  const files = fs.readdirSync(contractsDir).filter((f) => f.endsWith('.md'));
  const contracts = [];
  const prefixOrder = { A: 0, O: 1, V: 2, C: 3 };

  for (const file of files) {
    const fullPath = path.join(contractsDir, file);
    const content = fs.readFileSync(fullPath, 'utf8');
    const lines = content.split('\n');

    let id = '';
    let view = '';
    let endpoint = '';

    for (const line of lines) {
      if (line.startsWith('# ') && !id) {
        const match = line.match(/^# ((?:[VACO])-\d{2})\s+—\s+(.+)$/);
        if (match) {
          id = match[1];
          view = match[2];
          continue;
        }
      }
      if (line.startsWith('- Endpoint:') && !endpoint) {
        const match = line.match(/^- Endpoint:\s*(.+)$/);
        if (match) {
          endpoint = extractRouteText(match[1]);
          break;
        }
      }
    }

    if (id) {
      contracts.push({ id, view, endpoint, file });
    }
  }

  return contracts.sort((a, b) => {
    const prefixA = a.id.charAt(0);
    const prefixB = b.id.charAt(0);
    const numA = parseInt(a.id.match(/\d+/)?.[0] || '0', 10);
    const numB = parseInt(b.id.match(/\d+/)?.[0] || '0', 10);

    if (prefixOrder[prefixA] !== prefixOrder[prefixB]) {
      return prefixOrder[prefixA] - prefixOrder[prefixB];
    }
    return numA - numB;
  });
}

function generateScreenInventory(screens, missingIds) {
  const lines = [];
  lines.push('<!-- GENERATED by tools/build-design-index.mjs — do not edit -->');
  lines.push('');
  lines.push('| SCR | Name | Route | File |');
  lines.push('|---|---|---|---|');

  for (const s of screens) {
    const link = `[${s.file}](./screen-inventory/${s.file})`;
    lines.push(
      `| ${escapePipe(s.id)} | ${escapePipe(s.name)} | ${escapePipe(s.route)} | ${escapePipe(link)} |`,
    );
  }

  if (missingIds.length > 0) {
    lines.push('');
    lines.push('## Missing');
    lines.push('');
    lines.push(missingIds.map((id) => `- ${escapePipe(id)}`).join('\n'));
  }

  return lines.join('\n') + '\n';
}

function generateContractInventory(contracts) {
  const lines = [];
  lines.push('<!-- GENERATED by tools/build-design-index.mjs — do not edit -->');
  lines.push('');
  lines.push('| Id | View | Endpoint | File |');
  lines.push('|---|---|---|---|');

  for (const c of contracts) {
    const link = `[${c.file}](./view-data-contracts/${c.file})`;
    lines.push(
      `| ${escapePipe(c.id)} | ${escapePipe(c.view)} | ${escapePipe(c.endpoint)} | ${escapePipe(link)} |`,
    );
  }

  return lines.join('\n') + '\n';
}

function getMissingScreenIds() {
  const existingFiles = fs
    .readdirSync(screensDir)
    .filter((f) => f.startsWith('SCR-') && f.endsWith('.md'));
  const existingNumbers = new Set();
  for (const f of existingFiles) {
    const num = parseInt(f.match(/SCR-(\d+)/)?.[1] || '0', 10);
    if (num >= 1 && num <= 17) existingNumbers.add(num);
  }

  const missing = [];
  for (let i = 1; i <= 17; i++) {
    if (!existingNumbers.has(i)) {
      missing.push(`SCR-${i.toString().padStart(2, '0')}`);
    }
  }
  return missing;
}

function main() {
  const checkMode = process.argv.includes('--check');
  const screens = readScreenFiles();
  const contracts = readContractFiles();
  const missingIds = getMissingScreenIds();

  const screenContent = generateScreenInventory(screens, missingIds);
  const contractContent = contracts.length > 0 ? generateContractInventory(contracts) : null;

  if (checkMode) {
    let differs = false;

    if (fs.existsSync(outputScreen)) {
      const current = fs.readFileSync(outputScreen, 'utf8');
      if (current !== screenContent) differs = true;
    } else {
      differs = true;
    }

    if (contractContent && fs.existsSync(outputContracts)) {
      const current = fs.readFileSync(outputContracts, 'utf8');
      if (current !== contractContent) differs = true;
    } else if (contractContent && !fs.existsSync(outputContracts)) {
      differs = true;
    } else if (!contractContent && fs.existsSync(outputContracts)) {
      differs = true;
    }

    if (differs) {
      console.log('Index differs from generated content (manual edit or stale index)');
      process.exit(1);
    } else {
      console.log('Index matches generated content');
      process.exit(0);
    }
  } else {
    fs.writeFileSync(outputScreen, screenContent, 'utf8');
    if (contractContent) {
      fs.writeFileSync(outputContracts, contractContent, 'utf8');
    }
    console.log('Generated docs/design/screen-inventory.md');
    if (contractContent) {
      console.log('Generated docs/design/view-data-contracts.md');
    }
  }
}

main();
